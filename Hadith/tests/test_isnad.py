from hadith_bot.isnad import parse_isnad


def names(chain):
    return [l.name_norm for l in chain.links]


def test_bukhari_first_hadith():
    s = ("حَدَّثَنَا الْحُمَيْدِيُّ عَبْدُاللَّهِ بْنُ الزُّبَيْرِ، قَالَ حَدَّثَنَا سُفْيَانُ، قَالَ حَدَّثَنَا يَحْيَى بْنُ سَعِيدٍ الأَنْصَارِيُّ، "
         "قَالَ أَخْبَرَنِي مُحَمَّدُ بْنُ إِبْرَاهِيمَ التَّيْمِيُّ، أَنَّهُ سَمِعَ عَلْقَمَةَ بْنَ وَقَّاصٍ اللَّيْثِيَّ، يَقُولُ سَمِعْتُ عُمَرَ بْنَ الْخَطَّابِ ـ رضى الله عنه ـ عَلَى الْمِنْبَرِ")
    chains = parse_isnad(s)
    assert len(chains) == 1
    assert names(chains[0]) == ["الحميدي عبدالله بن الزبير", "سفيان", "يحيي بن سعيد الانصاري", "محمد بن ابراهيم التيمي", "علقمه بن وقاص الليثي", "عمر بن الخطاب"]
    assert all(l.mode == "sama" for l in chains[0].links)


def test_relative_and_anana():
    s = "حَدَّثَنَا عَبْدُ اللَّهِ بْنُ يُوسُفَ، قَالَ أَخْبَرَنَا مَالِكٌ، عَنْ هِشَامِ بْنِ عُرْوَةَ، عَنْ أَبِيهِ، عَنْ عَائِشَةَ أُمِّ الْمُؤْمِنِينَ ـ رضى الله عنها ـ"
    c = parse_isnad(s)[0]
    assert names(c) == ["عبدالله بن يوسف", "مالك", "هشام بن عروه", "ابيه", "عايشه ام المومنين"]
    assert c.links[3].is_relative and c.links[3].mode == "anana"


def test_coordinated_narrators():
    s = "حَدَّثَنَا أَبُو بَكْرِ بْنُ أَبِي شَيْبَةَ، وَأَبُو كُرَيْبٍ، قَالاَ حَدَّثَنَا أَبُو مُعَاوِيَةَ، عَنِ الأَعْمَشِ، عَنْ أَبِي صَالِحٍ، عَنْ أَبِي هُرَيْرَةَ، قَالَ قَالَ رَسُولُ اللَّهِ صلى الله عليه وسلم"
    c = parse_isnad(s)[0]
    assert names(c) == ["ابو بكر بن ابي شيبه", "ابو معاويه", "الاعمش", "ابي صالح", "ابي هريره"]
    assert [a.name_norm for a in c.links[0].alternatives] == ["ابو كريب"]


def test_tahwil_explicit_join():
    s = "حَدَّثَنَا يَحْيَى بْنُ يَحْيَى، أَخْبَرَنَا هُشَيْمٌ، ح وَحَدَّثَنَا أَبُو بَكْرِ بْنُ أَبِي شَيْبَةَ، حَدَّثَنَا عَبْدُ اللَّهِ بْنُ إِدْرِيسَ، كِلاَهُمَا عَنْ حُصَيْنٍ، عَنْ سَالِمِ بْنِ أَبِي الْجَعْدِ، عَنْ جَابِرٍ"
    chains = parse_isnad(s)
    assert len(chains) == 2
    assert names(chains[0]) == ["يحيي بن يحيي", "هشيم", "حصين", "سالم بن ابي الجعد", "جابر"]
    assert names(chains[1]) == ["ابو بكر بن ابي شيبه", "عبدالله بن ادريس", "حصين", "سالم بن ابي الجعد", "جابر"]
    assert not chains[0].join_inferred


def test_tahwil_inferred_join():
    s = "وَحَدَّثَنِي زُهَيْرُ بْنُ حَرْبٍ، حَدَّثَنَا جَرِيرٌ، ح وَحَدَّثَنَا ابْنُ نُمَيْرٍ، حَدَّثَنَا أَبِي، حَدَّثَنَا الأَعْمَشُ، عَنْ أَبِي صَالِحٍ، عَنْ أَبِي هُرَيْرَةَ"
    chains = parse_isnad(s)
    assert chains[0].join_inferred
    assert names(chains[0])[-3:] == ["الاعمش", "ابي صالح", "ابي هريره"]
    assert chains[1].links[1].is_relative  # « حدثنا أبي »


def test_empty():
    assert parse_isnad(None) == []
    assert parse_isnad("") == []
